package main

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
)

type document struct {
	OpenAPI string                          `json:"openapi"`
	Paths   map[string]map[string]operation `json:"paths"`
}

type operation struct {
	OperationID string `json:"operationId"`
}

type route struct {
	Method string
	Path   string
	ID     string
}

func main() {
	raw, err := os.ReadFile("openapi.json")
	if err != nil {
		fail(err)
	}
	var spec document
	if err := json.Unmarshal(raw, &spec); err != nil {
		fail(err)
	}
	if !strings.HasPrefix(spec.OpenAPI, "3.1.") {
		fail(fmt.Errorf("OpenAPI version %q is not 3.1", spec.OpenAPI))
	}
	var routes []route
	seen := make(map[string]bool)
	httpMethods := map[string]bool{
		"get": true, "post": true, "put": true, "patch": true, "delete": true,
	}
	for path, methods := range spec.Paths {
		for method, operation := range methods {
			if !httpMethods[method] {
				continue
			}
			method = strings.ToUpper(method)
			if operation.OperationID == "" || seen[operation.OperationID] {
				fail(fmt.Errorf("operationId is empty or duplicated at %s %s", method, path))
			}
			seen[operation.OperationID] = true
			routes = append(routes, route{Method: method, Path: path, ID: operation.OperationID})
		}
	}
	sort.Slice(routes, func(i, j int) bool {
		if routes[i].Path == routes[j].Path {
			return routes[i].Method < routes[j].Method
		}
		return routes[i].Path < routes[j].Path
	})
	sum := sha256.Sum256(raw)
	var source strings.Builder
	source.WriteString("// Code generated by go generate ./api; DO NOT EDIT.\n\n")
	source.WriteString("package api\n\n")
	source.WriteString("type Operation struct {\n\tMethod string\n\tPath string\n\tID string\n}\n\n")
	fmt.Fprintf(&source, "const OpenAPIVersion = %q\n", spec.OpenAPI)
	fmt.Fprintf(&source, "const OpenAPISHA256 = %q\n\n", hex.EncodeToString(sum[:]))
	source.WriteString("var Operations = []Operation{\n")
	for _, route := range routes {
		fmt.Fprintf(
			&source, "\t{Method: %q, Path: %q, ID: %q},\n",
			route.Method, route.Path, route.ID,
		)
	}
	source.WriteString("}\n")
	formatted, err := format.Source([]byte(source.String()))
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile("contract.gen.go", formatted, 0o644); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
