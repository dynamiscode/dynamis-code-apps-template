func TestDirectRenderProducerIgnoresNonRenderingArguments(t *testing.T) {
	source := `package fixture
	type Component interface { Render() }
	type Opaque struct { Value any }
	type Concrete struct{}
	func (Concrete) Render() {}
	func checked(Opaque) Component { return Concrete{} }
	func unknown(Opaque) Component { return Concrete{} }
	func (Concrete) checked(Opaque) Component { return Concrete{} }
	func calls(data Opaque, c Concrete) {
		checked(data).Render()
		unknown(data).Render()
		c.checked(data).Render()
		alias := checked
		alias(data).Render()
	}`
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "fixture.go", source, 0)
	if err != nil {
		t.Fatal(err)
	}
	info := &types.Info{Uses: make(map[*ast.Ident]types.Object)}
	if _, err := (&types.Config{}).Check("fixture", fset, []*ast.File{file}, info); err != nil {
		t.Fatal(err)
	}
	var got []bool
	ast.Inspect(file, func(node ast.Node) bool {
		call, ok := node.(*ast.CallExpr)
		if !ok {
			return true
		}
		selector, ok := call.Fun.(*ast.SelectorExpr)
		if ok && selector.Sel.Name == "Render" {
			got = append(got, directRenderProducer(selector.X, info, map[string]map[string]bool{"fixture": {"checked": true}}))
		}
		return true
	})
	want := []bool{true, false, false, false}
	if len(got) != len(want) {
		t.Fatalf("got %v, want %v", got, want)
	}
	for i := range want {
		if got[i] != want[i] {
			t.Errorf("case %d: got %v, want %v", i, got[i], want[i])
		}
	}
}

func TestGeneratedSourceMapSeparatesHandwrittenRenderFacilities(t *testing.T) {
	source := `package fixture
import markup "github.com/a-h/templ"
templ view() {
	{{
		alias := markup.Raw
		_ = alias
	}}
	<span>view</span>
}`
	template, err := templparser.ParseString(source)
	if err != nil {
		t.Fatal(err)
	}
	var generated bytes.Buffer
	result, err := generator.Generate(template, &generated)
	if err != nil {
		t.Fatal(err)
	}
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "fixture.go", generated.Bytes(), 0)
	if err != nil {
		t.Fatal(err)
	}
	want := map[string]bool{"Raw": true, "GeneratedTemplate": false}
	ast.Inspect(file, func(node ast.Node) bool {
		selector, ok := node.(*ast.SelectorExpr)
		if !ok {
			return true
		}
		if expected, check := want[selector.Sel.Name]; check {
			position := fset.PositionFor(selector.Sel.Pos(), false)
			handwritten := handwrittenIdentifier(result.SourceMap, []byte(source), position, selector.Sel.Name)
			if handwritten != expected {
				t.Errorf("%s handwritten = %v, want %v", selector.Sel.Name, handwritten, expected)
			}
			delete(want, selector.Sel.Name)
		}
		return true
	})
	if len(want) > 0 {
		t.Fatalf("missing expected selector(s): %v", want)
	}
}

