func TestClosedConsumersPropagateDynamicAndRecursiveRenderSinks(t *testing.T) {
	const source = `package fixture
	type Component interface { Render() }
	type body struct{}
	func (body) Render() {}
	func leaf(data any) Component { return body{} }
	func exact(data any) Component { leaf(data).Render(); return body{} }
	func opaque(data any) Component { data.(Component).Render(); return body{} }
	func indirect(data any) Component { opaque(data).Render(); return body{} }
	func recursive(data any) Component { recursive(data).Render(); return body{} }
	func external(data any) Component { notTemplate(data).Render(); return body{} }
	func notTemplate(data any) Component { return body{} }
	`
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "fixture.go", source, 0)
	if err != nil {
		t.Fatal(err)
	}
	info := &types.Info{Types: map[ast.Expr]types.TypeAndValue{}, Uses: map[*ast.Ident]types.Object{}, Defs: map[*ast.Ident]types.Object{}}
	pkg, err := (&types.Config{}).Check("fixture", fset, []*ast.File{file}, info)
	if err != nil {
		t.Fatal(err)
	}
	known := map[string]map[string]bool{"fixture": {"leaf": true, "exact": true, "opaque": true, "indirect": true, "recursive": true, "external": true}}
	functions := make(map[*types.Func]typedFunction)
	for _, declaration := range file.Decls {
		if function, ok := declaration.(*ast.FuncDecl); ok {
			functions[info.Defs[function.Name].(*types.Func)] = typedFunction{function, info}
		}
	}
	closed := closedTemplateConsumers(functions, known, pkg.Scope().Lookup("Component").Type().Underlying().(*types.Interface))
	for name := range known["fixture"] {
		if got, want := closed(pkg.Scope().Lookup(name).(*types.Func)), name == "leaf" || name == "exact"; got != want {
			t.Errorf("%s: got %v, want %v", name, got, want)
		}
	}
}
