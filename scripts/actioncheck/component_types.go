// VerifyTypedComponentArguments rejects component values whose producer is not
// a checked templ declaration, except where Scanned validates the value.
func VerifyTypedComponentArguments(root string) error {
	absoluteRoot, err := filepath.Abs(root)
	if err != nil {
		return err
	}
	overlay := make(map[string][]byte)
	type sourceOrigin struct {
		mapping *templparser.SourceMap
		input   []byte
	}
	sourceOrigins := make(map[string]sourceOrigin)
	if err := filepath.WalkDir(filepath.Join(absoluteRoot, "internal/web"), func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() || !strings.HasSuffix(path, ".templ") {
			return nil
		}
		source, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		file, err := templparser.ParseString(string(source))
		if err != nil {
			return fmt.Errorf("parse %s: %w", path, err)
		}
		var generated bytes.Buffer
		result, err := generator.Generate(file, &generated, generator.WithFileName(path))
		if err != nil {
			return fmt.Errorf("generate %s: %w", path, err)
		}
		outputPath := strings.TrimSuffix(path, ".templ") + "_templ.go"
		overlay[outputPath] = generated.Bytes()
		sourceOrigins[outputPath] = sourceOrigin{result.SourceMap, source}
		return nil
	}); err != nil {
		return err
	}
	config := &packages.Config{Dir: absoluteRoot, Overlay: overlay, Mode: packages.NeedName | packages.NeedFiles | packages.NeedCompiledGoFiles | packages.NeedSyntax | packages.NeedTypes | packages.NeedTypesInfo}
	loaded, err := packages.Load(config, "./internal/web/...")
	if err != nil {
		return err
	}
	const module = "example.com/dynamis-code/apps-template/"
	known := make(map[string]map[string]bool)
	for _, pkg := range loaded {
		if len(pkg.Errors) != 0 {
			return fmt.Errorf("type-check %s: %s", pkg.PkgPath, pkg.Errors[0])
		}
		if !strings.HasPrefix(pkg.PkgPath, module) {
			return fmt.Errorf("unexpected component package %s", pkg.PkgPath)
		}
		known[pkg.PkgPath], err = templateNames(filepath.Join(root, strings.TrimPrefix(pkg.PkgPath, module)))
		if err != nil {
			return err
		}
	}
	var component *types.Interface
	for _, pkg := range loaded {
		for _, imported := range pkg.Types.Imports() {
			if imported.Path() == "github.com/a-h/templ" {
				if named, ok := imported.Scope().Lookup("Component").Type().Underlying().(*types.Interface); ok {
					component = named.Complete()
				}
			}
		}
	}
	if component == nil {
		return fmt.Errorf("templ.Component type unavailable")
	}
	expectedRoots, err := expectedListRoots(filepath.Join(absoluteRoot, "internal/web"))
	if err != nil {
		return err
	}
	reachable, functions, err := reachableListFunctions(loaded, module+"internal/web", expectedRoots)
	if err != nil {
		return err
	}
	goOrigins := indexRenderOrigins(loaded, known)
	closedConsumer := closedTemplateConsumers(functions, known, component)
	goOrigins.closed, goOrigins.component = closedConsumer, component
	var violations []error
	for _, pkg := range loaded {
		for i, file := range pkg.Syntax {
			origin, generated := sourceOrigins[pkg.CompiledGoFiles[i]]
			generatedContexts, generatedChildren := compiledChildInputs(file, pkg.TypesInfo)
			var scanner *ast.FuncDecl
			if pkg.PkgPath == actionattrsImportPath {
				for _, declaration := range file.Decls {
					if function, ok := declaration.(*ast.FuncDecl); ok && function.Recv == nil && function.Name.Name == "Scanned" {
						scanner = function
					}
				}
			}
			ast.Inspect(file, func(node ast.Node) bool {
				ident, ok := node.(*ast.Ident)
				if !ok {
					return true
				}
				object := pkg.TypesInfo.Uses[ident]
				opaqueGoSlot := !generated && object != nil && object.Pkg() != nil && object.Pkg().Path() == actionattrsImportPath && object.Name() == "Scanned"
				if !reservedRenderObject(object) && !opaqueGoSlot && !strings.HasPrefix(ident.Name, templGeneratedPrefix) && !generatedContexts[pkg.TypesInfo.ObjectOf(ident)] {
					return true
				}
				if scanner != nil && scanner.Pos() <= ident.Pos() && ident.Pos() < scanner.End() && object != nil && object.Name() == "ComponentFunc" {
					return true
				}
				position := pkg.Fset.PositionFor(ident.Pos(), false)
				if generated {
					if !handwrittenIdentifier(origin.mapping, origin.input, position, ident.Name) {
						return true
					}
				}
				violations = append(violations, fmt.Errorf("%s: handwritten use of reserved templ render facility %s", position, ident.Name))
				return true
			})
			if !generated {
				for _, use := range goRenderSelectors(file, pkg.TypesInfo, component) {
					method := use.selector
					if scanner != nil && scanner.Pos() <= method.Pos() && method.Pos() < scanner.End() {
						continue
					}
					if !use.direct || !goOrigins.safeGoRenderReceiver(method.X, pkg.TypesInfo) {
						violations = append(violations, fmt.Errorf("%s: unverified Go component render receiver", pkg.Fset.Position(method.Pos())))
						continue
					}
					producer := ast.Unparen(method.X).(*ast.CallExpr)
					callee := calledFunction(producer, pkg.TypesInfo)
					if callee != nil && !closedConsumer(callee) {
						for _, argument := range producer.Args {
							if !typedComponentArgumentSafe(argument, pkg.TypesInfo, component, known, true, closedConsumer, nil) {
								violations = append(violations, fmt.Errorf("%s: unverified Go component argument", pkg.Fset.Position(argument.Pos())))
							}
						}
					}
				}
				continue
			}
			for _, declaration := range file.Decls {
				function, ok := declaration.(*ast.FuncDecl)
				if !ok || function.Body == nil {
					continue
				}
				object, _ := pkg.TypesInfo.Defs[function.Name].(*types.Func)
				listRoot := reachable[object]
				forwarded := func(expression ast.Expr) bool {
					return goOrigins.forwardedTemplateInput(expression, pkg.TypesInfo, object)
				}
				children := compiledChildSlots(function.Body, pkg.TypesInfo)
				classes := compiledClassLists(function.Body, pkg.TypesInfo)
				ast.Inspect(function.Body, func(node ast.Node) bool {
					call, ok := node.(*ast.CallExpr)
					if !ok {
						return true
					}
					if packageFunction(call, pkg.TypesInfo, "github.com/a-h/templ/runtime", "RenderAttributes") {
						if len(call.Args) != 5 || !checkedAttributeSpread(call.Args[4], pkg.TypesInfo) {
							violations = append(violations, fmt.Errorf("%s: unverified templ attribute spread", pkg.Fset.Position(call.Pos())))
						}
					}
					if packageFunction(call, pkg.TypesInfo, "github.com/a-h/templ", "WithChildren") {
						var child *ast.Ident
						if len(call.Args) == 2 {
							child, _ = call.Args[1].(*ast.Ident)
						}
						if child == nil || !generatedChildren[pkg.TypesInfo.Uses[child]] {
							violations = append(violations, fmt.Errorf("%s: unverified templ children producer", pkg.Fset.Position(call.Pos())))
						}
					}
					if writesDynamicHTML(call, pkg.TypesInfo) {
						violations = append(violations, fmt.Errorf("%s: dynamic HTML or script attribute", pkg.Fset.Position(call.Pos())))
					}
					if packageFunction(call, pkg.TypesInfo, "github.com/a-h/templ", "RenderCSSItems") {
						var list *ast.Ident
						if len(call.Args) == 3 {
							list, _ = call.Args[2].(*ast.Ident)
						}
						if list == nil || !classes[pkg.TypesInfo.Uses[list]] {
							violations = append(violations, fmt.Errorf("%s: unverified templ CSS class expression", pkg.Fset.Position(call.Pos())))
						}
					}
					method, ok := call.Fun.(*ast.SelectorExpr)
					if !ok || method.Sel.Name != "Render" {
						return true
					}
					typ := pkg.TypesInfo.TypeOf(method.X)
					if typ == nil || !types.Implements(typ, component) {
						return true
					}
					if child, ok := method.X.(*ast.Ident); ok && children[pkg.TypesInfo.Uses[child]] {
						return true
					}
					producer, ok := method.X.(*ast.CallExpr)
					if ok && (isScannedCall(producer, pkg.TypesInfo) || packageFunction(producer, pkg.TypesInfo, "github.com/a-h/templ", "JSONScript")) {
						if listRoot && isScannedCall(producer, pkg.TypesInfo) {
							violations = append(violations, fmt.Errorf("%s: buffered component slot on a streaming list path", pkg.Fset.Position(producer.Pos())))
						}
						return true
					}
					if !ok || !directRenderProducer(producer, pkg.TypesInfo, known) {
						violations = append(violations, fmt.Errorf("%s: unverified component render receiver", pkg.Fset.Position(method.Pos())))
						return true
					}
					callee := calledFunction(producer, pkg.TypesInfo)
					if closedConsumer(callee) {
						return true
					}
					for index, arg := range producer.Args {
						if !typedComponentArgumentSafe(arg, pkg.TypesInfo, component, known, true, closedConsumer, forwarded) {
							_, identifier := arg.(*ast.Ident)
							if identifier && callee != nil && callee.Pkg() != nil && known[callee.Pkg().Path()][callee.Name()] && ignoresComponentFields(functions[callee], index, component) {
								continue
							}
							position := pkg.Fset.PositionFor(arg.Pos(), false)
							if written, ok := origin.mapping.TargetLinesToSource[uint32(position.Line-1)][uint32(position.Column-1)]; ok {
								position.Filename = strings.TrimSuffix(position.Filename, "_templ.go") + ".templ"
								position.Line, position.Column = int(written.Line+1), int(written.Col+1)
							}
							violations = append(violations, fmt.Errorf("%s: unverified component argument", position))
						}
					}
					return true
				})
			}
		}
	}
	return errors.Join(violations...)
}

type typedFunction struct {
	declaration *ast.FuncDecl
	info        *types.Info
}

func expectedListRoots(webDirectory string) (map[string]bool, error) {
	roots := map[string]bool{"memberListView": true, "memberResults": true}
	for _, feature := range []struct{ source, list, results string }{
		{"clients.go", "clientListView", "clientResults"},
		{"files.go", "fileListView", "fileResults"},
	} {
		info, err := os.Stat(filepath.Join(webDirectory, feature.source))
		if errors.Is(err, fs.ErrNotExist) {
			continue
		}
		if err != nil {
			return nil, err
		}
		if !info.Mode().IsRegular() {
			return nil, fmt.Errorf("unexpected list feature source kind: %s", feature.source)
		}
		roots[feature.list], roots[feature.results] = true, true
	}
	return roots, nil
}

func reachableListFunctions(packages []*packages.Package, webPath string, expected map[string]bool) (map[*types.Func]bool, map[*types.Func]typedFunction, error) {
	functions := make(map[*types.Func]typedFunction)
	var roots []*types.Func
	found := make(map[string]bool)
	for _, pkg := range packages {
		for _, file := range pkg.Syntax {
			for _, declaration := range file.Decls {
				function, ok := declaration.(*ast.FuncDecl)
				if !ok || function.Body == nil {
					continue
				}
				object, _ := pkg.TypesInfo.Defs[function.Name].(*types.Func)
				if object == nil {
					continue
				}
				functions[object] = typedFunction{function, pkg.TypesInfo}
				if pkg.PkgPath == webPath && function.Recv == nil {
					switch function.Name.Name {
					case "clientListView", "clientResults", "memberListView", "memberResults", "fileListView", "fileResults":
						if !expected[function.Name.Name] {
							return nil, nil, fmt.Errorf("unexpected list entry point %s", function.Name.Name)
						}
						found[function.Name.Name] = true
						roots = append(roots, object)
					}
				}
			}
		}
	}
	for name := range expected {
		if !found[name] {
			return nil, nil, fmt.Errorf("missing required list entry point %s", name)
		}
	}
	reachable := make(map[*types.Func]bool)
	for len(roots) > 0 {
		function := roots[len(roots)-1]
		roots = roots[:len(roots)-1]
		if reachable[function] {
			continue
		}
		reachable[function] = true
		body, ok := functions[function]
		if !ok {
			continue
		}
		ast.Inspect(body.declaration.Body, func(node ast.Node) bool {
			call, ok := node.(*ast.CallExpr)
			if !ok || isScannedCall(call, body.info) {
				return true
			}
			if called := calledFunction(call, body.info); called != nil {
				if _, ok := functions[called]; ok {
					roots = append(roots, called)
				}
			}
			return true
		})
	}
	return reachable, functions, nil
}

func ignoresComponentFields(function typedFunction, index int, component *types.Interface) bool {
	if function.declaration == nil || function.info == nil {
		return false
	}
	var parameter *types.Var
	position := 0
	for _, field := range function.declaration.Type.Params.List {
		if len(field.Names) == 0 {
			position++
			continue
		}
		for _, name := range field.Names {
			if position == index {
				parameter, _ = function.info.Defs[name].(*types.Var)
			}
			position++
		}
	}
	if parameter == nil {
		return false
	}
	valid := true
	var stack []ast.Node
	ast.Inspect(function.declaration.Body, func(node ast.Node) bool {
		if node == nil {
			stack = stack[:len(stack)-1]
			return true
		}
		if ident, ok := node.(*ast.Ident); ok && function.info.Uses[ident] == parameter {
			if len(stack) == 0 {
				valid = false
			} else if selector, ok := stack[len(stack)-1].(*ast.SelectorExpr); !ok || selector.X != ident {
				valid = false
			} else if _, ok := function.info.Uses[selector.Sel].(*types.Var); !ok || containsComponent(function.info.TypeOf(selector), component, make(map[types.Type]bool)) {
				valid = false
			}
		}
		stack = append(stack, node)
		return true
	})
	return valid
}

func calledFunction(call *ast.CallExpr, info *types.Info) *types.Func {
	var ident *ast.Ident
	switch function := call.Fun.(type) {
	case *ast.Ident:
		ident = function
	case *ast.SelectorExpr:
		ident = function.Sel
	}
	if ident == nil {
		return nil
	}
	function, _ := info.Uses[ident].(*types.Func)
	return function
}

func isScannedCall(call *ast.CallExpr, info *types.Info) bool {
	return packageFunction(call, info, actionattrsImportPath, "Scanned")
}

func typedComponentArgumentSafe(root ast.Expr, info *types.Info, component *types.Interface, known map[string]map[string]bool, containers bool, closedConsumer func(*types.Func) bool, forwarded func(ast.Expr) bool) bool {
	safe := true
	ast.Inspect(root, func(node ast.Node) bool {
		if !safe {
			return false
		}
		if expression, ok := node.(ast.Expr); ok && forwarded != nil && forwarded(expression) {
			return false
		}
		if call, ok := node.(*ast.CallExpr); ok && (isScannedCall(call, info) || checkedAttributeSpread(call, info)) {
			return false
		}
		if literal, ok := node.(*ast.CompositeLit); ok {
			_, isMap := info.TypeOf(literal).Underlying().(*types.Map)
			for _, element := range literal.Elts {
				if field, ok := element.(*ast.KeyValueExpr); ok {
					if isMap && !typedComponentArgumentSafe(field.Key, info, component, known, containers, closedConsumer, forwarded) {
						safe = false
						break
					}
					element = field.Value
				}
				if !typedComponentArgumentSafe(element, info, component, known, containers, closedConsumer, forwarded) {
					safe = false
					break
				}
			}
			return false
		}
		expression, ok := node.(ast.Expr)
		if !ok {
			return true
		}
		typ := info.TypeOf(expression)
		if typ == nil {
			return true
		}
		if ident, ok := expression.(*ast.Ident); ok && info.Uses[ident] == types.Universe.Lookup("nil") {
			return false
		}
		if !types.Implements(typ, component) {
			_, opaqueInterface := typ.Underlying().(*types.Interface)
			if containers && (opaqueInterface || containsComponent(typ, component, make(map[types.Type]bool))) {
				safe = false
				return false
			}
			if selector, ok := expression.(*ast.SelectorExpr); containers && ok {
				if selection := info.Selections[selector]; selection != nil && selection.Kind() == types.FieldVal {
					return false
				}
			}
			if call, ok := expression.(*ast.CallExpr); ok {
				if _, scalar := types.Unalias(typ).(*types.Basic); scalar {
					// A scalar result cannot carry a component. Any render
					// side effects are checked separately at their sinks.
					return false
				}
				for _, argument := range call.Args {
					if !typedComponentArgumentSafe(argument, info, component, known, containers, closedConsumer, forwarded) {
						safe = false
						break
					}
				}
				return false
			}
			return true
		}
		call, ok := expression.(*ast.CallExpr)
		if !ok {
			safe = false
			return false
		}
		if !directRenderProducer(call, info, known) {
			safe = false
			return false
		}
		if closedConsumer != nil && closedConsumer(calledFunction(call, info)) {
			return false
		}
		for _, argument := range call.Args {
			if !typedComponentArgumentSafe(argument, info, component, known, containers, closedConsumer, forwarded) {
				safe = false
				break
			}
		}
		return false
	})
	return safe
}

func containsComponent(typ types.Type, component *types.Interface, seen map[types.Type]bool) bool {
	if seen[typ] {
		return false
	}
	seen[typ] = true
	if types.Implements(typ, component) {
		return true
	}
	switch value := typ.Underlying().(type) {
	case *types.Interface:
		return true
	case *types.Pointer:
		return containsComponent(value.Elem(), component, seen)
	case *types.Slice:
		return containsComponent(value.Elem(), component, seen)
	case *types.Array:
		return containsComponent(value.Elem(), component, seen)
	case *types.Chan:
		return containsComponent(value.Elem(), component, seen)
	case *types.Signature:
		return containsComponent(value.Results(), component, seen)
	case *types.Tuple:
		for i := 0; i < value.Len(); i++ {
			if containsComponent(value.At(i).Type(), component, seen) {
				return true
			}
		}
	case *types.Map:
		return containsComponent(value.Key(), component, seen) || containsComponent(value.Elem(), component, seen)
	case *types.Struct:
		for i := 0; i < value.NumFields(); i++ {
			if containsComponent(value.Field(i).Type(), component, seen) {
				return true
			}
		}
	}
	return false
}
